package main

import (
	"bytes"
	"fmt"
	"io"
	"net"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/rivo/tview"
)

const previewEvents = "/.galaxy-ide-preview/events"

type webPreview struct {
	dir, base string
	files     *os.Root
	server    *http.Server
	mu        sync.Mutex
	revision  uint64
	changed   chan struct{}
}

func startWebPreview(dir string) (*webPreview, error) {
	files, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		_ = files.Close()
		return nil, err
	}
	p := &webPreview{dir: dir, base: "http://" + listener.Addr().String(), files: files, changed: make(chan struct{})}
	p.server = &http.Server{Handler: p, ReadHeaderTimeout: 5 * time.Second, IdleTimeout: 15 * time.Second}
	go func() { _ = p.server.Serve(listener) }()
	return p, nil
}

func (p *webPreview) close() {
	_ = p.server.Close()
	_ = p.files.Close()
}

func (p *webPreview) saved(path string) {
	if rel, err := filepath.Rel(p.dir, path); err != nil || !filepath.IsLocal(rel) {
		return
	}
	p.mu.Lock()
	p.revision++
	close(p.changed)
	p.changed = make(chan struct{})
	p.mu.Unlock()
}

func (p *webPreview) snapshot() (uint64, <-chan struct{}) {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.revision, p.changed
}

func (p *webPreview) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		w.WriteHeader(http.StatusMethodNotAllowed)
		return
	}
	// Only the URL generated by the IDE can read the local project.
	if r.Host != strings.TrimPrefix(p.base, "http://") {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Cache-Control", "no-store")
	if r.URL.Path == previewEvents {
		rev, changed := p.snapshot()
		w.Header().Set("Content-Type", "text/event-stream")
		if r.Method == http.MethodHead {
			return
		}
		_, _ = io.WriteString(w, ": connected\n\n")
		if err := http.NewResponseController(w).Flush(); err != nil {
			return
		}
		if r.URL.Query().Get("since") == strconv.FormatUint(rev, 10) {
			select {
			case <-r.Context().Done():
				return
			case <-changed:
			}
		}
		_, _ = io.WriteString(w, "event: reload\ndata: saved\n\n")
		return
	}
	requestPath := strings.TrimPrefix(r.URL.Path, "/")
	// Never serve repository internals or accept paths that leave the preview root.
	for part := range strings.SplitSeq(requestPath, "/") {
		if strings.HasPrefix(part, ".") {
			http.NotFound(w, r)
			return
		}
	}
	name := filepath.FromSlash(requestPath)
	if strings.HasSuffix(r.URL.Path, "/") {
		name = filepath.Join(name, "index.html")
	}
	ext := strings.ToLower(filepath.Ext(name))
	if ext == ".html" || ext == ".htm" {
		if f, err := p.files.Open(name); err == nil {
			defer f.Close()
			if info, err := f.Stat(); err == nil && info.Mode().IsRegular() && info.Size() <= maxFileSize {
				rev, _ := p.snapshot()
				if page, err := io.ReadAll(io.LimitReader(f, maxFileSize+1)); err == nil && len(page) <= maxFileSize {
					script := fmt.Sprintf(`<script>new EventSource(%q).addEventListener("reload",()=>location.reload());</script>`, previewEvents+"?since="+strconv.FormatUint(rev, 10))
					page = append(page, []byte(script)...)
					w.Header().Set("Content-Type", "text/html; charset=utf-8")
					http.ServeContent(w, r, filepath.Base(name), time.Time{}, bytes.NewReader(page))
					return
				}
			}
		}
	}
	http.FileServerFS(p.files.FS()).ServeHTTP(w, r)
}

func previewEntry(root, file string) string {
	rel, err := filepath.Rel(root, file)
	if err != nil || !filepath.IsLocal(rel) {
		rel = ""
	}
	if toolsFor(file).id == "html" && rel != "" {
		return rel
	}
	for dir := filepath.Dir(rel); ; dir = filepath.Dir(dir) {
		index := filepath.Join(dir, "index.html")
		if info, err := os.Stat(filepath.Join(root, index)); err == nil && info.Mode().IsRegular() {
			return index
		}
		if dir == "." {
			return ""
		}
	}
}

func (i *ide) openWebPreview() {
	file := i.active.disk.path
	root := i.root
	if file != "" {
		root = i.nativeProject().root
	}
	if i.preview != nil && i.preview.dir != root {
		i.preview.close()
		i.preview = nil
	}
	if i.preview == nil {
		p, err := startWebPreview(root)
		if err != nil {
			i.notify("웹 미리보기 · " + err.Error())
			return
		}
		i.preview = p
	}
	entry := (&url.URL{Path: "/" + filepath.ToSlash(previewEntry(root, file))}).EscapedPath()
	address := i.preview.base + entry
	text := tview.NewTextView().SetDynamicColors(true).SetText(
		"아래 주소를 눌러 브라우저에서 여세요. 파일을 저장하면 자동으로 갱신됩니다.\n\n" +
			"[aqua::u:" + address + "]" + address + "[:::-]")
	buttons := tview.NewForm().AddButton("편집기로", i.dismiss).AddButton("미리보기 종료", func() {
		i.dismiss()
		i.stopWebPreview()
	})
	box := tview.NewFlex().SetDirection(tview.FlexRow).AddItem(text, 0, 1, false).AddItem(buttons, 3, 0, true)
	box.SetBorder(true).SetTitle(" 웹 미리보기 ")
	i.showDialog(box, 88, 10)
	i.notify(address)
}

func (i *ide) stopWebPreview() {
	if i.preview != nil {
		i.preview.close()
		i.preview = nil
		i.notify("웹 미리보기를 종료했습니다")
	}
}
